// Microsoft Fabric Warehouse Storage Insights mock data generator
export type StorageUnit = "MB" | "GB" | "TB";

export interface StorageMetric {
  id: string;
  label: string;
  value: number;
  unit: StorageUnit;
  description: string;
  filterCategoryIds?: string[];
  percentageOfTotal?: number;
}

export interface StorageCategory {
  id: string;
  name: string;
  sizeGb: number;
  description: string;
  billingState: string;
  cleanupBehavior: string;
  relatedCapability: string;
}

export interface TableStorageRecord {
  id: string;
  schema: string;
  tableName: string;
  tableType: "Fact" | "Dimension" | "Snapshot" | "Staging" | "Audit" | "Aggregate";
  totalGb: number;
  activeGb: number;
  historicalGb: number;
  softDeletedGb: number;
  fileCount: number;
  expiredFiles: number;
  nonReferencedFiles: number;
  lastModified: string;
  lastAccessed: string;
  queriesLast30Days: number;
  growth30dPct: number;
  owner: string;
  reviewRecommended?: boolean;
}

export interface TrendPoint {
  day: string;
  totalGb: number;
  activeGb: number;
  historicalGb: number;
  systemGb: number;
}

export interface Observation {
  id: string;
  title: string;
  detail: string;
  severity: "info" | "warning";
}

export interface QueryViewDefinition {
  viewName: string;
  purpose: string;
  columns: string[];
  sampleQuery: string;
  rows: Array<Record<string, string | number>>;
  dashboardTarget: StorageTab;
}

export interface AlertRule {
  id: string;
  ruleName: string;
  enabled: boolean;
  severity: "Information" | "Warning" | "Critical";
  threshold: string;
  destination: string;
  lastTriggered: string;
}

export type StorageTab =
  | "overview"
  | "breakdown"
  | "tables"
  | "trends"
  | "query-views"
  | "retention"
  | "alerts";

